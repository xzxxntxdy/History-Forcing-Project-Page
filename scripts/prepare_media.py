#!/usr/bin/env python3
"""Prepare lossless web MP4s, lightweight hero previews, posters, and metadata.

Run from any directory with Python 3, ffmpeg, and ffprobe on PATH:
    python scripts/prepare_media.py
    python scripts/prepare_media.py --source-root /path/to/paper-workspace
    python scripts/prepare_media.py --prune
    python scripts/prepare_media.py --previews-only
    python scripts/prepare_media.py --web-only

Only assets/videos, assets/posters, assets/media-sources.json, and media-data.js
inside this project are written. Original source media is never changed.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path
import re
import shutil
import struct
import subprocess


SITE = Path(__file__).resolve().parents[1]
SHORT_SCENES = [
    ("03_glacial_cave", "Glacial cave"),
    ("05_seoul_violinist", "Seoul violinist"),
    ("01_hong_kong_tram", "Hong Kong tram"),
    ("06_desert_carnival", "Desert carnival"),
]
LONG_SCENES = [
    ("p0554_park_yoga__MemRoPE__seed5__1f043c28.mp4", "yoga", "Park yoga"),
    ("p0311_pottery_wheel__MemRoPE__seed2__8b3ae36f.mp4", "pottery", "Pottery wheel"),
    ("p0273_making_dumplings__MemRoPE__seed0__3899dd8a.mp4", "dumplings", "Making dumplings"),
    ("p0303_playing_acoustic_guitar__MemRoPE__seed0__abd27aa7.mp4", "guitar", "Acoustic guitar"),
    ("p0316_brushing_teeth_at_mirror__MemRoPE__seed15__eced57a3.mp4", "brushing", "Mirror reflection"),
    ("p0777_chef_plating__MemRoPE__seed3__d99068a6.mp4", "chef", "Chef at work"),
]
WORLD_SCENES = [
    ("03_milk_pouring", "Pouring milk"),
    ("01_watercolor", "Watercolor painting"),
    ("05_sand_filling", "Filling with sand"),
]
PREVIEW_SCENES = [
    ("short", "03_glacial_cave", "glacial-cave", 16.0),
    ("long", "yoga", "yoga", 16.0),
    ("world", "03_milk_pouring", "milk", 16.0),
]


def checksum(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_prompt(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig").strip()


def probe_video(path: Path) -> dict:
    return json.loads(subprocess.check_output([
        "ffprobe", "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=width,height,codec_name,pix_fmt,avg_frame_rate,nb_frames:format=duration",
        "-of", "json", str(path),
    ], text=True, encoding="utf-8"))


def stream_hashes(path: Path) -> list[str]:
    output = subprocess.check_output([
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-i", str(path),
        "-map", "0", "-c", "copy", "-f", "streamhash", "-hash", "sha256", "-",
    ], text=True, encoding="utf-8")
    return [line.strip() for line in output.splitlines() if line.strip() and not line.startswith("#")]


def has_faststart(path: Path) -> bool:
    positions = {}
    with path.open("rb") as handle:
        length = path.stat().st_size
        while handle.tell() < length:
            position = handle.tell()
            header = handle.read(8)
            if len(header) != 8:
                break
            size, kind = struct.unpack(">I4s", header)
            if size == 1:
                size = struct.unpack(">Q", handle.read(8))[0]
            if size == 0:
                size = length - position
            if size < 8:
                raise ValueError(f"Invalid MP4 box in {path.name}")
            positions[kind] = position
            handle.seek(position + size)
    return b"moov" in positions and b"mdat" in positions and positions[b"moov"] < positions[b"mdat"]


def write_media_data(data: dict) -> None:
    (SITE / "media-data.js").write_text(
        "// Generated by scripts/prepare_media.py; source media remains unchanged.\n"
        "window.HF_MEDIA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )


def prepare_previews(data: dict) -> list[dict]:
    previews = []
    for group, scene_id, filename, limit in PREVIEW_SCENES:
        item = next(item for item in data[group] if item["id"] == scene_id)
        source_relative = (item.get("ours") or item["src"]).split("?", 1)[0]
        source = SITE / source_relative
        target = SITE / "assets" / "videos" / "previews" / f"{filename}.mp4"
        target.parent.mkdir(parents=True, exist_ok=True)
        duration = min(float(item["duration"]), limit)
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
            "-i", str(source), "-t", str(duration), "-an",
            "-vf", "scale=640:-2:flags=lanczos,setsar=1", "-r", "16",
            "-c:v", "libx264", "-preset", "slow", "-crf", "26",
            "-maxrate", "1000k", "-bufsize", "2000k",
            "-pix_fmt", "yuv420p", "-profile:v", "high", "-level:v", "3.1",
            "-g", "32", "-keyint_min", "32", "-sc_threshold", "0",
            "-movflags", "+faststart", str(target),
        ], check=True)
        if not has_faststart(target):
            raise ValueError(f"Preview is missing faststart: {target.name}")
        output_hash = checksum(target)
        relative = target.relative_to(SITE).as_posix()
        item["preview"] = f"{relative}?v={output_hash[:12]}"
        if data.get("heroWorld", {}).get("id") == scene_id:
            data["heroWorld"]["preview"] = item["preview"]
        probe = probe_video(target)
        stream = probe["streams"][0]
        previews.append({
            "source": source_relative, "source_sha256": checksum(source),
            "file": relative, "sha256": output_hash, "bytes": target.stat().st_size,
            "width": stream["width"], "height": stream["height"],
            "frame_rate": stream["avg_frame_rate"], "frames": int(stream["nb_frames"]),
            "duration": float(probe["format"]["duration"]), "start_seconds": 0,
            "faststart": True, "keyframe_interval_seconds": 2,
            "encoding": "H.264 high / yuv420p, CRF 26, 640px wide, no audio",
        })
    return previews


def prepare_comparison_web(data: dict) -> list[dict]:
    """Create smaller lossy comparison copies; original URLs/files stay intact."""
    records = []
    for group, directory in (("short", "15s"), ("world", "world")):
        for item in data[group]:
            paired = []
            for role in ("baseline", "ours"):
                relative_source = item[role].split("?", 1)[0]
                source = SITE / relative_source
                source_probe = probe_video(source)
                original = source_probe["streams"][0]
                # Integer scaling preserves the exact display aspect ratio and
                # even chroma dimensions. 832x480 stays native; 1280x704 -> 960x528.
                divisor = math.gcd(original["width"], original["height"])
                ratio_width = original["width"] // divisor
                ratio_height = original["height"] // divisor
                factor = min(divisor, 960 // ratio_width)
                while (ratio_width * factor) % 2 or (ratio_height * factor) % 2:
                    factor -= 1
                width, height = ratio_width * factor, ratio_height * factor
                target = SITE / "assets" / "videos" / "web" / directory / f"{item['id']}-{role}.mp4"
                target.parent.mkdir(parents=True, exist_ok=True)
                subprocess.run([
                    "ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source), "-an",
                    "-vf", f"scale={width}:{height}:flags=lanczos,setsar=1", "-r", "16",
                    "-c:v", "libx264", "-preset", "slow", "-crf", "21",
                    "-maxrate", "1100k", "-bufsize", "2200k",
                    "-pix_fmt", "yuv420p", "-profile:v", "high", "-level:v", "3.1",
                    "-g", "16", "-keyint_min", "16", "-sc_threshold", "0",
                    "-video_track_timescale", "16000", "-movie_timescale", "16000",
                    "-movflags", "+faststart", str(target),
                ], check=True)
                output_probe = probe_video(target)
                stream = output_probe["streams"][0]
                if any(stream[key] != original[key] for key in ("avg_frame_rate", "nb_frames")):
                    raise ValueError(f"Web derivative changed frame rate or frame count: {target.name}")
                if source_probe["format"]["duration"] != output_probe["format"]["duration"]:
                    raise ValueError(f"Web derivative changed duration: {target.name}")
                if not has_faststart(target):
                    raise ValueError(f"Web derivative is missing faststart: {target.name}")
                measure = subprocess.run([
                    "ffmpeg", "-hide_banner", "-i", str(source), "-i", str(target),
                    "-lavfi", f"[0:v]scale={width}:{height}:flags=lanczos,setsar=1[ref];[1:v][ref]ssim",
                    "-an", "-f", "null", "-",
                ], check=True, capture_output=True, text=True, encoding="utf-8")
                scores = re.findall(r"All:([0-9.]+)", measure.stderr)
                if not scores:
                    raise ValueError(f"SSIM measurement unavailable: {target.name}")
                output_hash = checksum(target)
                relative = target.relative_to(SITE).as_posix()
                item[f"{role}Web"] = f"{relative}?v={output_hash[:12]}"
                duration = float(output_probe["format"]["duration"])
                record = {
                    "scene": item["id"], "role": role,
                    "source": relative_source, "source_sha256": checksum(source),
                    "file": relative, "sha256": output_hash, "bytes": target.stat().st_size,
                    "source_width": original["width"], "source_height": original["height"],
                    "width": width, "height": height, "frame_rate": stream["avg_frame_rate"],
                    "frames": int(stream["nb_frames"]), "duration": duration,
                    "average_bit_rate": round(target.stat().st_size * 8 / duration),
                    "faststart": True, "keyframe_interval_seconds": 1,
                    "ssim_vs_resized_original": float(scores[-1]),
                    "encoding": "H.264 high / yuv420p, CRF 21, maxrate 1100k, bufsize 2200k, at most 960px wide, no audio",
                }
                records.append(record)
                paired.append(record)
            if any(paired[0][key] != paired[1][key] for key in ("width", "height", "frame_rate", "frames", "duration", "encoding")):
                raise ValueError(f"Web pair has mismatched settings or timing: {item['id']}")
    return records


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=SITE.parents[1])
    parser.add_argument("--prune", action="store_true", help="Remove stale copied MP4/JPEG assets only inside this project's media folders")
    parser.add_argument("--previews-only", action="store_true", help="Regenerate hero previews from existing site videos without touching full videos")
    parser.add_argument("--web-only", action="store_true", help="Generate smaller comparison copies without touching original full videos")
    args = parser.parse_args()
    root = args.source_root.resolve()
    for executable in ("ffmpeg", "ffprobe"):
        if shutil.which(executable) is None:
            parser.error(f"{executable} is required on PATH")
    if args.previews_only and args.web_only:
        parser.error("Select only one derivative-only mode")
    if args.web_only:
        if args.prune:
            parser.error("--web-only cannot be combined with --prune")
        text = (SITE / "media-data.js").read_text(encoding="utf-8")
        data = json.loads(text.split("window.HF_MEDIA = ", 1)[1].strip().removesuffix(";"))
        web = prepare_comparison_web(data)
        write_media_data(data)
        manifest_path = SITE / "assets" / "media-sources.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        manifest["schema_version"] = 3
        manifest["comparison_web"] = web
        web_note = "Web comparison videos are smaller lossy copies with identical settings for both sides; original-quality files are retained for reproducible generation."
        ssim_note = "Web SSIM compares against original frames resized with Lanczos to the Web dimensions; it is not a losslessness claim."
        for note in (web_note, ssim_note):
            if note not in manifest["notes"]:
                manifest["notes"].append(note)
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Prepared {len(web)} Web comparison copies: {sum(item['bytes'] for item in web):,} bytes.")
        return
    if args.previews_only:
        if args.prune:
            parser.error("--previews-only cannot be combined with --prune")
        text = (SITE / "media-data.js").read_text(encoding="utf-8")
        data = json.loads(text.split("window.HF_MEDIA = ", 1)[1].strip().removesuffix(";"))
        previews = prepare_previews(data)
        write_media_data(data)
        manifest_path = SITE / "assets" / "media-sources.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        manifest["previews"] = previews
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Prepared {len(previews)} hero previews: {sum(item['bytes'] for item in previews):,} bytes.")
        return
    source_dir = root / "exports" / "videos"
    if not source_dir.is_dir():
        parser.error(f"Missing exports/videos inside {root}")

    records = []
    data = {"short": [], "long": [], "world": []}

    def copy_video(source: Path, group: str, name: str) -> tuple[str, str, float]:
        target = SITE / "assets" / "videos" / group / f"{name}.mp4"
        poster = SITE / "assets" / "posters" / group / f"{name}.jpg"
        target.parent.mkdir(parents=True, exist_ok=True)
        poster.parent.mkdir(parents=True, exist_ok=True)
        source_hash = checksum(source)
        temporary = target.with_suffix(".faststart.mp4")
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
            "-map", "0", "-c", "copy", "-movflags", "+faststart", str(temporary),
        ], check=True)
        probe = probe_video(source)
        output_probe = probe_video(temporary)
        if probe != output_probe:
            raise ValueError(f"Lossless remux changed stream geometry, timing, or frame count: {target.name}")
        hashes = stream_hashes(source)
        if hashes != stream_hashes(temporary):
            raise ValueError(f"Lossless remux changed encoded stream bytes: {target.name}")
        if not has_faststart(temporary):
            raise ValueError(f"Lossless remux is missing faststart: {target.name}")
        temporary.replace(target)
        output_hash = checksum(target)
        stream = probe["streams"][0]
        duration = float(probe["format"]["duration"])
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
            "-ss", "0.5", "-i", str(source), "-frames:v", "1",
            "-vf", "scale='min(960,iw)':-2", "-q:v", "3", str(poster),
        ], check=True)
        video_path = target.relative_to(SITE).as_posix()
        poster_path = poster.relative_to(SITE).as_posix()
        records.append({
            "source": source.relative_to(root).as_posix(),
            "file": video_path,
            "source_sha256": source_hash,
            "sha256": output_hash,
            "encoded_stream_sha256": hashes,
            "faststart": True,
            "bytes": target.stat().st_size,
            "width": stream["width"],
            "height": stream["height"],
            "codec": stream["codec_name"],
            "frame_rate": stream["avg_frame_rate"],
            "frames": int(stream["nb_frames"]),
            "duration": duration,
            "poster": poster_path,
            "poster_timestamp": 0.5,
            "poster_sha256": checksum(poster),
        })
        return f"{video_path}?v={output_hash[:12]}", poster_path, duration

    for folder, title in SHORT_SCENES:
        scene = source_dir / "15svideo" / folder
        baseline, baseline_poster, baseline_duration = copy_video(scene / "baseline.mp4", "15s", f"{folder}-baseline")
        ours, poster, duration = copy_video(scene / "ours.mp4", "15s", f"{folder}-ours")
        if abs(baseline_duration - duration) > 1e-6:
            raise ValueError(f"Paired video durations differ: {folder}")
        data["short"].append({
            "id": folder, "title": title, "prompt": read_prompt(scene / "prompt.txt"),
            "baseline": baseline, "ours": ours, "baselinePoster": baseline_poster,
            "poster": poster, "duration": duration,
        })

    long_dir = source_dir / "60svideo" / "ours_all_60s_videos_20261028"
    with (long_dir / "video_index.csv").open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    for filename, scene_id, title in LONG_SCENES:
        row = next(row for row in rows if filename in row.values())
        video, poster, duration = copy_video(long_dir / filename, "60s", scene_id)
        data["long"].append({
            "id": scene_id, "title": title, "prompt": row["prompt"],
            "src": video, "poster": poster, "duration": duration,
        })

    for folder, title in WORLD_SCENES:
        scene = source_dir / "world_model_demos" / folder
        baseline, baseline_poster, baseline_duration = copy_video(scene / "baseline.mp4", "world", f"{folder}-baseline")
        ours, poster, duration = copy_video(scene / "ours.mp4", "world", f"{folder}-ours")
        if abs(baseline_duration - duration) > 1e-6:
            raise ValueError(f"Paired video durations differ: {folder}")
        data["world"].append({
            "id": folder, "title": title, "prompt": read_prompt(scene / "prompt.txt"),
            "baseline": baseline, "ours": ours, "baselinePoster": baseline_poster,
            "poster": poster, "duration": duration,
        })

    hero_scene = data["world"][0]
    data["heroWorld"] = {
        "id": hero_scene["id"], "title": hero_scene["title"],
        "prompt": hero_scene["prompt"], "src": hero_scene["ours"],
        "poster": hero_scene["poster"], "duration": hero_scene["duration"],
    }

    previews = prepare_previews(data)
    web = prepare_comparison_web(data)
    write_media_data(data)
    (SITE / "assets" / "media-sources.json").write_text(json.dumps({
        "schema_version": 3,
        "source_root": "paper workspace",
        "video_count": len(records),
        "total_video_bytes": sum(record["bytes"] for record in records),
        "notes": [
            "Full videos are losslessly remuxed from selected exports/videos sources with moov before mdat (faststart).",
            "source_sha256 hashes the source MP4; sha256 hashes the served MP4. Container bytes differ while encoded stream hashes match.",
            "Full-video codec, dimensions, frame rate, frame count, and duration are verified unchanged. No full video is re-encoded.",
            "Hero previews are separate 640px-wide H.264 derivatives with 2-second keyframe intervals; comparison playback uses the smaller Web copies listed below, while long videos keep their original quality.",
            "Web comparison videos are smaller lossy copies with identical settings for both sides; original-quality files are retained for reproducible generation.",
            "Web SSIM compares against original frames resized with Lanczos to the Web dimensions; it is not a losslessness claim.",
            "Posters are JPEG frames extracted at 0.5 seconds, at most 960 pixels wide.",
            "Long-rollout examples last 62.8125 seconds.",
            "World demos display separate Baseline and History Forcing streams with identical paired durations and matched Web encoding settings.",
            "Prompt text is copied from the source exports; some world demos use a changing prompt schedule.",
        ],
        "videos": records,
        "previews": previews,
        "comparison_web": web,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if args.prune:
        project_root = SITE.resolve()
        expected = {
            (SITE / record[key]).resolve()
            for record in records for key in ("file", "poster")
        }
        expected.update((SITE / preview["file"]).resolve() for preview in previews)
        expected.update((SITE / record["file"]).resolve() for record in web)
        removed = 0
        for relative_dir, extension in (("assets/videos", ".mp4"), ("assets/posters", ".jpg")):
            media_root = (SITE / relative_dir).resolve()
            if project_root not in media_root.parents:
                raise ValueError(f"Media directory resolves outside this project: {relative_dir}")
            for candidate in media_root.rglob("*"):
                if not candidate.is_file() or candidate.suffix.lower() != extension:
                    continue
                resolved = candidate.resolve()
                if media_root not in resolved.parents or project_root not in resolved.parents:
                    raise ValueError(f"Refusing to remove a path outside the media directory: {candidate.name}")
                if resolved not in expected:
                    candidate.unlink()
                    removed += 1
        print(f"Removed {removed} stale copied media assets inside this project.")
    print(f"Prepared {len(records)} lossless full videos and {len(records)} posters.")
    print(f"Video bytes: {sum(record['bytes'] for record in records):,}")
    print(f"Hero preview bytes: {sum(preview['bytes'] for preview in previews):,}")
    print(f"Web comparison bytes: {sum(record['bytes'] for record in web):,}")
    print("Wrote media-data.js and assets/media-sources.json.")


if __name__ == "__main__":
    main()
